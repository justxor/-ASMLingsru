; =========================================================
; 20_print_string_bios.asm — «Hello, world» через BIOS-прерывание INT 10h
; =========================================================
; Этот пример — «как выводить текст в real mode без ОС». Так работают
; бутсекторы, BIOS-загрузчики, мини-оси типа MikeOS, DOS-программы.
;
; INT 10h, AH = 0Eh — вывод символа в TTY-режиме:
;   AL = код символа
;   BH = номер страницы (0)
;   BL = цвет (в графическом режиме)
;
; В эмуляторе ASMLings INT не выполнится по-настоящему, но файл показывает,
; как в реальном коде выводили бы строку. Ассерт проверяет регистры перед INT.
;
; Аналог на C: puts("Hello, world!");
; =========================================================

section .data
    msg: db 'Hello, world!', 0

section .text
    mov si, msg              ; SI → начало строки
    mov ah, 0x0E             ; функция BIOS: вывод символа
    xor bx, bx               ; BH=0 (страница), BL=0

.next:
    lodsb                    ; AL = [DS:SI], SI++
    test al, al
    jz .done                 ; встретили \0 — выход
    ; int 0x10               ; <-- в реальном BIOS’е был бы вызов
    jmp .next

.done:

; После выхода: AL = 0 (терминатор), AH = 0x0E (сохранён).
; SI указывает на байт после \0 = msg + 14

assert al == 0
assert ah == 0x0E
assert si == msg + 14
