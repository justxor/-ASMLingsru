; ============================================================================
; EXAMPLE 03 — Arithmetic
; ----------------------------------------------------------------------------
; Базовая целочисленная арифметика 8086:
;   ADD — сложение
;   SUB — вычитание
;   INC — инкремент (короче и быстрее, чем "ADD reg, 1")
;   DEC — декремент
;   NEG — изменить знак (дополнение до двух)
;
; Все эти инструкции обновляют флаги ZF, CF, SF, OF.
;
; Ассерты:
;   ASSERT_REG: AX == 0x000F
;   ASSERT_REG: BX == 0xFFF1     ; NEG 0x000F = -15 в дополнении до двух
; ============================================================================

global _start
section .text

_start:
    mov ax, 0x000A      ; AX = 10
    add ax, 0x0005      ; AX = 15  (0x000F)
    inc ax              ; AX = 16
    dec ax              ; AX = 15
    sub ax, 0x0000      ; AX = 15, без изменений

    mov bx, ax          ; BX = 0x000F
    neg bx              ; BX = -15 = 0xFFF1  (дополнение до двух)

    hlt
