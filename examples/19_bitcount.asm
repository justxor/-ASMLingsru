; =========================================================
; 19_bitcount.asm — подсчёт единичных битов (popcount)
; =========================================================
; Алгоритм Kernighan'a: x = x & (x - 1) сбрасывает самый правый единичный бит.
; Считаем, сколько раз мы это сделали — это и есть количество единичных битов.
; Сложность: O(popcount), а не O(разрядность).
;
; Аналог на C:
;   int popcount(uint16_t x) {
;       int c = 0;
;       while (x) { x &= x - 1; c++; }
;       return c;
;   }
; =========================================================

section .text
    mov ax, 0xB37F           ; бинарно: 1011 0011 0111 1111 → 11 единиц
    xor cx, cx               ; cx = счётчик

.loop:
    test ax, ax
    jz .done                 ; все биты сброшены
    mov bx, ax
    dec bx                   ; bx = x - 1
    and ax, bx               ; x = x & (x-1)
    inc cx                   ; выбросили один бит
    jmp .loop

.done:

assert cx == 11
