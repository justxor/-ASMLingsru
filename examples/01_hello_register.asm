; ============================================================================
; EXAMPLE 01 — Hello, Register!
; ----------------------------------------------------------------------------
; Самая первая программа на ассемблере: загрузить значение в регистр.
;
; Что демонстрирует:
;   - синтаксис NASM (section .text, _start, hlt)
;   - инструкцию MOV с непосредственным операндом
;   - использование hex-литералов
;
; Ассерт:
;   ASSERT_REG: AX == 0x1337
; ============================================================================

global _start
section .text

_start:
    mov ax, 0x1337      ; AX = 0x1337
    hlt                 ; останавливаем CPU
