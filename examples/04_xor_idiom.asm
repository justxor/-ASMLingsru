; ============================================================================
; EXAMPLE 04 — XOR-Zero Idiom
; ----------------------------------------------------------------------------
; "xor reg, reg" — самая известная идиома в x86-ассемблере.
; Любое число XOR с самим собой даёт ноль:  A ^ A = 0.
;
; Зачем это вместо "mov reg, 0"?
;   - Машинный код короче: 2 байта против 3.
;   - На современных CPU специально оптимизировано (zero-idiom recognition).
;   - Сбрасывает ложные зависимости в out-of-order ядре.
;
; Заодно показываем, как XOR-ом инвертировать конкретные биты —
; еще одно его применение.
;
; Ассерты:
;   ASSERT_REG: AX == 0x0000
;   ASSERT_REG: BX == 0x0000
;   ASSERT_REG: CX == 0xF0F0    ; инверсия 0x0F0F через XOR с 0xFFFF
; ============================================================================

global _start
section .text

_start:
    xor ax, ax          ; AX = 0  (идиома обнуления)
    xor bx, bx          ; BX = 0

    mov cx, 0x0F0F
    xor cx, 0xFFFF      ; инвертируем все биты: 0x0F0F -> 0xF0F0

    hlt
