; =========================================================
; 12_memcpy.asm — копирование блока памяти через MOVSB / REP
; =========================================================
; На 8086 есть специальные строковые инструкции:
;   MOVSB — [ES:DI] := [DS:SI], затем SI++/DI++ или SI--/DI-- (в зависимости от DF)
;   REP   — префикс, повторяет инструкцию CX раз
;
; Это почти прямой аналог memcpy() из C, но без цикла в явном виде.
;
; Аналог на C:
;   void memcpy(char *dst, const char *src, size_t n) {
;       while (n--) *dst++ = *src++;
;   }
; =========================================================

section .data
    src: db 'ABCDEFGH', 0     ; 9 байт (с нулем)
    dst: times 9 db 0          ; 9 пустых байт

section .text
    cld                  ; DF = 0 → SI/DI будут расти
    mov si, src          ; SI → источник
    mov di, dst          ; DI → приёмник
    mov cx, 9            ; сколько байт копировать

    rep movsb            ; одной строкой — весь memcpy!

    ; проверка: первые два байта dst должны быть 'A' и 'B'
    mov al, [dst]
    mov ah, [dst+1]

assert al == 'A'
assert ah == 'B'
assert cx == 0
