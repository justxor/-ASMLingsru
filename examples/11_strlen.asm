; =========================================================
; 11_strlen.asm — вычисление длины ASCIIZ-строки
; =========================================================
; Идея: проходим по строке, пока не встретим байт 0.
; CX — счётчик, SI — указатель на текущий байт.
; Результат остаётся в AX.
;
; Аналог на C:
;   size_t strlen(const char *s) {
;       size_t n = 0;
;       while (*s++) n++;
;       return n;
;   }
; =========================================================

section .data
    msg: db 'Hello, ASMLings!', 0   ; ASCIIZ, длина = 16

section .text
    mov si, msg          ; SI → начало строки
    xor cx, cx           ; CX = 0 (счётчик)

.next:
    mov al, [si]         ; читаем байт
    test al, al          ; это терминатор?
    jz .done             ; да — выходим
    inc si               ; нет — сдвигаемся
    inc cx               ; и увеличиваем счётчик
    jmp .next

.done:
    mov ax, cx           ; возвращаем длину в AX

assert ax == 16
