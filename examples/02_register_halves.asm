; ============================================================================
; EXAMPLE 02 — Register Halves (AH / AL)
; ----------------------------------------------------------------------------
; AX — это 16-битный регистр, который физически состоит из двух 8-битных:
;
;        15      8 7       0
;       +---------+---------+
;   AX  |   AH    |   AL    |
;       +---------+---------+
;
; Записывая AH и AL по отдельности, мы собираем нужное 16-битное значение
; по байтам.
;
; Ассерт:
;   ASSERT_REG: AX == 0xABCD
; ============================================================================

global _start
section .text

_start:
    mov ah, 0xAB        ; старший байт: AX = 0xAB00
    mov al, 0xCD        ; младший байт: AX = 0xABCD
    hlt
