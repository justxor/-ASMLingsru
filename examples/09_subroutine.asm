; ============================================================================
; EXAMPLE 09 — Подпрограмма: CALL, RET, сохранение регистров
; ----------------------------------------------------------------------------
; CALL label:
;   1) кладёт на стек адрес следующей инструкции (return address)
;   2) прыгает на label
;
; RET:
;   снимает со стека return address и прыгает по нему
;
; Подпрограмма "square" вычисляет AX = AX * AX. Внутри она портит DX
; (потому что MUL пишет в DX:AX), поэтому она аккуратно его сохраняет
; через PUSH/POP — это callee-saved стратегия.
;
; Передача аргумента: через AX. Возврат значения: через AX.
;
; План:
;   AX = 12  ->  square  ->  AX = 144 (0x0090)
;   DX до и после вызова должен остаться 0xDEAD (мы его проверяем)
;
; Ассерты:
;   ASSERT_REG: AX == 0x0090
;   ASSERT_REG: DX == 0xDEAD    ; не пострадал, потому что подпрограмма сохранила DX
; ============================================================================

global _start
section .text

_start:
    mov dx, 0xDEAD      ; сторожевое значение
    mov ax, 12
    call square         ; AX = 12 * 12 = 144 = 0x0090
    hlt

; ---- подпрограмма ----
square:
    push dx             ; сохранили DX
    mul ax              ; DX:AX = AX * AX. AX = 144, DX портится.
    pop  dx             ; восстановили DX
    ret
