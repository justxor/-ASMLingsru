; =========================================================
; 14_atoi.asm — преобразование ASCII-строки в число
; =========================================================
; Идея классического atoi():
;   acc = 0
;   для каждого символа c пока он в '0'..'9':
;       acc = acc*10 + (c - '0')
;
; Ключевые приёмы:
; * умножение на 10 реализовано через сдвиги: x*10 = (x<<3) + (x<<1)
; * проверка диапазона цифр — двумя cmp + jb/ja
;
; Аналог на C:
;   int atoi(const char *s);
; =========================================================

section .data
    num_str: db '1337', 0

section .text
    mov si, num_str      ; SI → строка
    xor ax, ax           ; AX = аккумулятор результата

.loop:
    mov bl, [si]         ; взяли символ
    cmp bl, '0'
    jb .done             ; ниже '0' — не цифра
    cmp bl, '9'
    ja .done             ; выше '9' — не цифра

    sub bl, '0'          ; BL = числовое значение (0..9)
    xor bh, bh           ; BX = BL (zero-extend)

    ; AX = AX*10 = (AX<<3) + (AX<<1)
    mov cx, ax
    shl ax, 3            ; AX = AX*8
    shl cx, 1            ; CX = AX_old*2
    add ax, cx           ; AX = AX*8 + AX*2 = AX*10

    add ax, bx           ; AX += digit
    inc si               ; следующий символ
    jmp .loop

.done:

assert ax == 1337
