; =========================================================
; 16_strrev.asm — реверс строки на месте (in-place)
; =========================================================
; Находим два указателя: SI → начало, DI → последний символ.
; Пока SI < DI — обмениваем байты. Классика.
;
; XCHG — атомарный обмен двух регистров, но для памяти берём через два mov.
; =========================================================

section .data
    str: db 'ASMLings', 0     ; длина 8

section .text
    mov si, str              ; SI → первый символ
    mov di, str + 7          ; DI → последний символ

.swap:
    cmp si, di
    jge .done                ; указатели сошлись
    mov al, [si]
    mov bl, [di]
    mov [si], bl             ; обменяли
    mov [di], al
    inc si
    dec di
    jmp .swap

.done:
    mov al, [str]
    mov bl, [str+1]
    mov cl, [str+7]

assert al == 's'             ; было 'A', стало 's'
assert bl == 'g'             ; было 'S', стало 'g'
assert cl == 'A'             ; было 's', стало 'A'
