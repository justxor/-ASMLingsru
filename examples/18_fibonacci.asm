; =========================================================
; 18_fibonacci.asm — числа Фибоначчи (итеративно)
; =========================================================
; F(0)=0, F(1)=1, F(n)=F(n-1)+F(n-2).
; Итеративный вариант — самый быстрый, O(n) время и O(1) память.
;
; Держим два предыдущих числа в AX и BX, обновляем в паре.
;
; Аналог на C:
;   uint16_t fib(uint16_t n) {
;       uint16_t a = 0, b = 1;
;       while (n--) { uint16_t t = a + b; a = b; b = t; }
;       return a;
;   }
; =========================================================

section .text
    mov cx, 10               ; хотим F(10) = 55
    xor ax, ax               ; a = 0
    mov bx, 1                ; b = 1

.loop:
    test cx, cx
    jz .done                 ; n == 0 — выход
    mov dx, ax               ; dx = a
    add dx, bx               ; dx = a + b
    mov ax, bx               ; a = b
    mov bx, dx               ; b = a+b
    dec cx
    jmp .loop

.done:

assert ax == 55              ; F(10) = 55
