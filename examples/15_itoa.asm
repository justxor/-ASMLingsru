; =========================================================
; 15_itoa.asm — преобразование числа в десятичную строку
; =========================================================
; Классический трюк: делим число на 10, цифры получаем в обратном
; порядке — поэтому складываем их в стек, а потом POPом вытаскиваем
; и записываем в буфер. Стек — это бесплатный reverse!
;
; DIV r/m16 делит DX:AX на r/m16:
;   AX = частное
;   DX = остаток (это и есть очередная цифра)
;
; Аналог на C:
;   void itoa(uint16_t n, char *buf);
; =========================================================

section .data
    buf: times 8 db 0
    div10: dw 10

section .text
    mov ax, 1337         ; число для печати
    xor cx, cx           ; CX = счётчик цифр

.split:
    xor dx, dx           ; DX = 0 (важно перед div!)
    div word [div10]     ; AX = AX/10, DX = AX%10
    push dx              ; сохраняем цифру в стек
    inc cx               ; всего цифр +1
    test ax, ax
    jnz .split           ; есть ещё цифры — продолжаем

    mov di, buf          ; DI → начало буфера
.write:
    pop ax               ; вытаскиваем цифру (в правильном порядке)
    add al, '0'          ; переводим в ASCII
    mov [di], al
    inc di
    loop .write          ; CX-- и прыжок если CX!=0

    mov al, [buf]
    mov ah, [buf+1]
    mov bl, [buf+2]
    mov bh, [buf+3]

assert al == '1'
assert ah == '3'
assert bl == '3'
assert bh == '7'
