; ============================================================================
; EXAMPLE 06 — MUL и DIV (DX:AX)
; ----------------------------------------------------------------------------
; MUL operand:  DX:AX = AX * operand     (беззнаковое 16x16 -> 32 бита)
; DIV operand:  AX = DX:AX / operand
;               DX = DX:AX % operand     (беззнаковое 32 / 16 -> 16:16)
;
; КРИТИЧЕСКИ ВАЖНО:
;   - MUL пишет результат сразу в пару DX:AX (старшее слово в DX, младшее в AX).
;   - DIV использует пару DX:AX как делимое. Если делишь маленькое число,
;     ОБЯЗАТЕЛЬНО обнули DX перед DIV — иначе эмулятор вернёт мусор или
;     выкинет "divide overflow".
;
; План:
;   1) посчитать 7 * 9 = 63           ->  AX = 0x003F, DX = 0
;   2) посчитать 100 / 7 = 14 (ост 2) ->  AX = 0x000E, DX = 0x0002
;   3) сохранить частное в BX, остаток в CX
;
; Ассерты:
;   ASSERT_REG: BX == 0x000E    ; частное
;   ASSERT_REG: CX == 0x0002    ; остаток
; ============================================================================

global _start
section .text

_start:
    ; --- умножение ---
    mov ax, 7
    mov si, 9           ; используем SI как множитель
    mul si              ; DX:AX = 7 * 9 = 63 = 0x003F

    ; --- деление ---
    xor dx, dx          ; ВАЖНО: очистить старшее слово делимого
    mov ax, 100
    mov di, 7
    div di              ; AX = 100 / 7 = 14, DX = 100 % 7 = 2

    mov bx, ax          ; BX = частное
    mov cx, dx          ; CX = остаток

    hlt
