; ============================================================================
; EXAMPLE 08 — Memory: чтение, запись, косвенная адресация
; ----------------------------------------------------------------------------
; В этом примере:
;   1) объявляем данные в секции .data через DW
;   2) читаем 16-битное слово в AX
;   3) пишем обратно изменённое значение
;   4) демонстрируем косвенную адресацию через BX
;
; Память в x86 little-endian:
;   DW 0x1234  лежит в памяти как байты [0x34, 0x12]
;
; Ассерты:
;   ASSERT_REG: AX == 0x002A    ; 42 десятичное
;   ASSERT_MEM: counter == 0x002A
; ============================================================================

global _start
section .text

_start:
    ; --- прямое чтение по метке ---
    mov ax, [counter]   ; AX = 0x0028  (40 в counter)
    add ax, 2           ; AX = 0x002A  (42)

    ; --- прямая запись по метке ---
    mov [counter], ax   ; counter = 0x002A

    ; --- косвенная адресация: тот же эффект через BX ---
    mov bx, counter     ; BX = адрес counter
    mov dx, [bx]        ; DX = слово по этому адресу
    ; (DX теперь тоже 0x002A — просто для демонстрации)

    hlt

section .data
counter: dw 40          ; 0x0028 — стартовое значение
