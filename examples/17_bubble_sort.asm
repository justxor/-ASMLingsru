; =========================================================
; 17_bubble_sort.asm — пузырьковая сортировка массива байтов
; =========================================================
; Классика: внешний цикл по проходам, внутренний — по соседям.
; Для n элементов нужно (n-1) проходов, в каждом (n-1) сравнений.
;
; Аналог на C:
;   for (i = 0; i < n-1; i++)
;       for (j = 0; j < n-1; j++)
;           if (a[j] > a[j+1]) swap(a[j], a[j+1]);
; =========================================================

section .data
    arr: db 5, 2, 8, 1, 9, 3, 7, 4, 6, 0
    n equ 10

section .text
    mov cx, n - 1            ; внешний цикл: n-1 проходов
.outer:
    push cx                  ; сохраняем внешний счётчик
    mov si, arr              ; SI → a[0]
    mov cx, n - 1            ; внутренний цикл

.inner:
    mov al, [si]             ; al = a[j]
    mov bl, [si + 1]         ; bl = a[j+1]
    cmp al, bl
    jbe .no_swap             ; уже в порядке
    mov [si], bl             ; иначе обмен
    mov [si + 1], al
.no_swap:
    inc si
    loop .inner

    pop cx
    loop .outer

    ; проверка: крайние элементы
    mov al, [arr]            ; должно быть 0
    mov bl, [arr + 9]        ; должно быть 9
    mov cl, [arr + 4]        ; середина — 4

assert al == 0
assert bl == 9
assert cl == 4
