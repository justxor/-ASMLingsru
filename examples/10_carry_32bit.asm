; ============================================================================
; EXAMPLE 10 — 32-битное сложение на 16-битном CPU (Carry Flag + ADC)
; ----------------------------------------------------------------------------
; Это самый "взрослый" пример. Демонстрирует, как сложить два 32-битных числа,
; имея только 16-битные регистры.
;
; Идея: разбиваем каждое число на пару (high, low) 16-битных слов.
;   - Складываем младшие половинки обычным ADD. Если сумма не помещается
;     в 16 бит, ADD взводит флаг CF (Carry).
;   - Складываем старшие половинки через ADC ("ADD with Carry") — он
;     добавляет ещё и текущий CF, тем самым "донося" перенос из младшей
;     половины в старшую.
;
; Это тот же приём, которым в школе складывают столбиком два многозначных
; числа: запоминаешь перенос в уме и добавляешь к следующему разряду.
;
; A = 0x0001_FFFF   (DX_hi = 0x0001, AX_lo = 0xFFFF)
; B = 0x0000_0001   (CX_hi = 0x0000, BX_lo = 0x0001)
;
; A + B = 0x0002_0000
;   младшее: FFFF + 0001 = 0000, CF = 1
;   старшее: 0001 + 0000 + CF = 0002
;
; Ассерты:
;   ASSERT_REG: AX == 0x0000
;   ASSERT_REG: DX == 0x0002
; ============================================================================

global _start
section .text

_start:
    ; --- загружаем A в DX:AX ---
    mov dx, 0x0001      ; A high
    mov ax, 0xFFFF      ; A low

    ; --- загружаем B в CX:BX ---
    mov cx, 0x0000      ; B high
    mov bx, 0x0001      ; B low

    ; --- собственно 32-битное сложение ---
    add ax, bx          ; low:   0xFFFF + 0x0001 = 0x0000, CF=1
    adc dx, cx          ; high:  0x0001 + 0x0000 + CF(1) = 0x0002

    hlt
