; ============================================================================
; EXAMPLE 07 — Цикл: сумма 1+2+...+10
; ----------------------------------------------------------------------------
; LOOP label — короткая запись для "DEC CX + JNZ label":
;   декрементирует CX и прыгает, если CX != 0.
;
; Используем CX и как счётчик итераций, и как текущее слагаемое.
; Гаусс знает, что 1+2+...+10 = 55 = 0x37.
;
; Подводный камень: если CX = 0 ДО входа в LOOP, тело выполнится 65536 раз
; (DEC превратит 0 в 0xFFFF). Защита — инструкция JCXZ перед циклом.
;
; Ассерты:
;   ASSERT_REG: AX == 0x0037    ; 55 десятичное
;   ASSERT_REG: CX == 0x0000    ; цикл закончился
; ============================================================================

global _start
section .text

_start:
    xor ax, ax          ; сумма = 0
    mov cx, 10          ; счётчик 10..1

    jcxz done           ; если cx уже 0 — не входить в цикл

.next:
    add ax, cx          ; сумма += текущее значение CX
    loop .next          ; cx--, прыгаем пока cx != 0

done:
    hlt
